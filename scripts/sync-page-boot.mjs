import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const css = readFileSync('assets/css/page-boot.css', 'utf8');
const js = readFileSync('assets/js/page-boot.js', 'utf8');
const block = `<!-- StudyLab early appearance/loading: generated by scripts/sync-page-boot.mjs -->
<style id="sl-page-boot">${css}</style>
<script>${js}</script>
<!-- /StudyLab early appearance/loading -->`;

// Four rings only, each a 90-degree arc; direction and speed set in page-boot.css.
// Center the same infinity icon used to install StudyLab.
const visual = `<!-- StudyLab boot overlay: generated by scripts/sync-page-boot.mjs -->
<div id="sl-boot-loader" role="status" aria-live="polite" aria-label="StudyLab loading">
  <div class="sl-boot-orbits" aria-hidden="true">
    <span class="sl-boot-ring"></span>
    <span class="sl-boot-ring"></span>
    <span class="sl-boot-ring"></span>
    <span class="sl-boot-ring"></span>
    <img class="sl-boot-icon" src="assets/icon/studylab-192.png?v=sl-infinity-20261127" width="104" height="104" alt="" decoding="async" fetchpriority="high">
  </div>
  <strong class="sl-boot-name">StudyLab</strong>
</div>
<!-- /StudyLab boot overlay -->`;

const oldHead = /<!-- StudyLab early appearance\/loading:[\s\S]*?<!-- \/StudyLab early appearance\/loading -->/;
const oldOverlay = /<!-- StudyLab boot overlay:[\s\S]*?<!-- \/StudyLab boot overlay -->/;

for (const file of readdirSync('.').filter(x => x.endsWith('.html'))) {
  let html = readFileSync(file, 'utf8');
  if (!html.includes('assets/js/main.js')) continue;
  html = oldHead.test(html)
    ? html.replace(oldHead, block)
    : html.replace(/<meta\s+charset=[^>]+>/i, match => match + '\n' + block);
  // Idempotent: same result after every build, without duplicated loader nodes.
  // Remove the previous generated block together with its surrounding newline.
  // The canonical body insertion uses exactly one newline before/after the markup.
  html = html.replace(/\r?\n?<!-- StudyLab boot overlay:[\s\S]*?<!-- \/StudyLab boot overlay -->[ \t]*\r?\n?/, '\n');
  if (!/<body\b[^>]*>/i.test(html)) throw new Error('Missing body tag in ' + file);
  html = html.replace(/(<body\b[^>]*>)[ \t]*\r?\n*/i, '$1\n' + visual + '\n');
  writeFileSync(file, html);
}
