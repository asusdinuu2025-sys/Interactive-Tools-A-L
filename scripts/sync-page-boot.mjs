import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
const css = readFileSync('assets/css/page-boot.css', 'utf8');
const js = readFileSync('assets/js/page-boot.js', 'utf8');
const block = `<!-- StudyLab early appearance/loading: generated by scripts/sync-page-boot.mjs -->\n<style id="sl-page-boot">${css}</style>\n<script>${js}</script>\n<!-- /StudyLab early appearance/loading -->`;
for (const file of readdirSync('.').filter(x => x.endsWith('.html'))) {
  let html = readFileSync(file, 'utf8');
  if (!html.includes('assets/js/main.js')) continue;
  const old = /<!-- StudyLab early appearance\/loading:[\s\S]*?<!-- \/StudyLab early appearance\/loading -->/;
  html = old.test(html) ? html.replace(old, block) : html.replace(/<meta\s+charset=[^>]+>/i, match => match + '\n' + block);
  writeFileSync(file, html);
}
