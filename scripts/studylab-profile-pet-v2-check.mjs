/* Focused, read-only checks for the November StudyLab profile and pet refinement. */
import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
const read = p => readFileSync(p,"utf8");
const viewer=read("assets/js/studylab-profile-view.js");
const account=read("assets/js/studylab-account.js");
const avatar=read("assets/js/studylab-avatar.js");
const followCss=read("assets/css/studylab-follow.css");
const analytics=read("assets/js/study-room-analytics.js");
const bioMigration=read("supabase/migrations/20261115173500_bio_35_characters.sql");
const home=read("index.html");
const room=read("study-room.html");
assert.match(viewer,/avatarPick = element\("label","sl-pv-avatar-upload"/);
assert.match(viewer,/avatarPick\.append\(avatarFile\)/);
assert.match(viewer,/avatarFile\.type = "file"/);
assert.match(viewer,/avatarFile\.accept = "image\/jpeg,image\/png,image\/webp"/);
assert.doesNotMatch(viewer,/avatarFile\.hidden = true/);
assert.match(avatar,/bucket\.upload\(path,blob,\{/);
assert.match(avatar,/bucket\.update\(path,blob,/);
assert.match(avatar,/Photo upload failed/);
assert.match(avatar,/verifyPublicImage\(photoUrl\)/);
assert.match(avatar,/waitForVisibleProfile\(uid,photoUrl\)/);
assert.match(avatar,/img\.loading = "eager"/);
assert.match(avatar,/img\.style\.opacity = "0"/);
assert.doesNotMatch(avatar,/img\.loading = "lazy"/);
assert.doesNotMatch(avatar,/img\.hidden = true/);
assert.match(viewer,/const count=Array\.from\(bioInput\.value\.trim\(\)\)\.length/);
assert.match(viewer,/count\+" \/ 35 characters"/);
assert.match(account,/Array\.from\(cleanBio\)\.length > 35/);
assert.match(bioMigration,/new\.bio is distinct from old\.bio/);
assert.match(bioMigration,/drop constraint if exists studylab_profiles_bio_word_limit/);
assert.match(bioMigration,/char_length\(coalesce\(new\.bio,''\)\) > 35/);
assert.match(viewer,/listBackdrop=element\("div","sl-pv-list-backdrop"\)/);
assert.match(viewer,/listBackdrop\.append\(listPanel\)/);
assert.match(viewer,/dialog\.append\(header,identity,avatarEditor,bioSummary,bioEditor,counts,actions,followAction,joined,viewStatus\)/);
assert.match(viewer,/function closeList\(\)/);
assert.match(viewer,/avatarRemove = button\("sl-pv-avatar-remove","Use default avatar"\)/);
assert.match(viewer,/bioEditToggle=button\("sl-pv-bio-edit-toggle"/);
assert.match(viewer,/avatarToggle=button\("sl-pv-avatar-toggle"/);
assert.match(viewer,/window\.StudyLabAvatar\?\.decorate\(avatar,profile\.user_id\)/);
assert.match(followCss,/\.sl-pv-list-backdrop/);
assert.match(followCss,/scrollbar-color/);
assert.match(followCss,/Bahnschrift SemiBold/);
assert.match(followCss,/\.homepage-greeting-name > \.sl-name-mark/);
assert.match(analytics,/target\.scrollIntoView\(\{behavior:reduce\?"auto":"smooth",block:"start"\}\)/);
assert.match(read("assets/css/study-room-illustrated-glass.css"),/scroll-margin-top:95px/);
for(const petPath of ["assets/js/studylab-pet.js","assets/js/studylab-pet-room.js"]){
  const pet=read(petPath);
  assert.match(pet,/PET_VISIT_PREFIX="studylab-pet-visit-v2:"/);
  assert.match(pet,/async function welcomeKnownStudent\(\)/);
  assert.match(pet,/const profile=await account\.getProfile\(\)/);
  assert.match(pet,/state\.brain\.recentThoughts/);
  assert.match(pet,/function contextSectionReaction\(event\)/);
  assert.match(pet,/prefers-reduced-motion: reduce/);
  assert.match(pet,/welcomeKnownStudent\(\)/);
  if (petPath.includes("pet-room.js")) assert.match(pet,/goalCelebrationUntil/);
}
assert.match(home,/studylab-pet\.js\?v=20261115-brain-v2/);
assert.match(room,/studylab-pet-room\.js\?v=20261115-brain-v2/);
console.log("StudyLab compact profile, avatar, smooth navigation and Pet v2 checks passed.");
