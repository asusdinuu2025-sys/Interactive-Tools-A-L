"use strict";
const assert=require("node:assert/strict");
const {PRICES,initial,apply,snapshot}=require("./studylab-plus-lifecycle.cjs");
const now=Date.UTC(2026,10,25),month=30*86400000;
const order={id:"test-order",environment:"sandbox",months:1,amountMinor:19900,currency:"LKR"};
const event=(overrides={})=>({id:"e1",orderId:order.id,environment:"sandbox",currency:"LKR",amountMinor:19900,kind:"confirmed",subscriptionId:"test-sub",paymentId:"p1",at:now,paidUntil:now+month,nextBillingAt:now+month,...overrides});
assert.deepEqual(PRICES,{1:19900,3:49900,12:179900});
assert.throws(()=>initial({...order,environment:"live"}),/sandbox/);
assert.throws(()=>initial({...order,amountMinor:1}),/sandbox/);
let s=initial(order);
assert.equal(snapshot(s,now).sandboxAccess,false);
for(const e of [{environment:"live"},{currency:"USD"},{amountMinor:1},{orderId:"other"},{paidUntil:now},{subscriptionId:""}])assert.throws(()=>apply(s,event(e)));
s=apply(s,event());
assert.equal(snapshot(s,now).sandboxAccess,true);
assert.equal(snapshot(s,now).liveAccess,false);
assert.equal(snapshot(s,now).confirmedMinor,19900);
assert.deepEqual(apply(s,event()),s);
assert.throws(()=>apply(s,event({paidUntil:now+2*month})),/Conflicting event/);
assert.throws(()=>apply(s,event({id:"conflict",paidUntil:now+2*month})),/Conflicting payment/);
assert.equal(snapshot(apply(s,event({id:"duplicate"})),now).confirmedMinor,19900);
assert.throws(()=>apply(s,event({id:"foreign",subscriptionId:"other"})),/Subscription mismatch/);
s=apply(s,event({id:"e2",kind:"failed",paymentId:"p2",at:now+month-1}));
assert.equal(snapshot(s,now+month-1).sandboxAccess,true);
assert.equal(s.state,"past_due");
s=apply(s,event({id:"e3",paymentId:"p2",at:now+month,paidUntil:now+2*month,nextBillingAt:now+2*month}));
assert.equal(s.state,"active");
assert.equal(snapshot(s,now+month).confirmedMinor,39800);
s=apply(s,event({id:"e4",kind:"cancelled",at:now+month+1}));
assert.equal(s.state,"cancelled");assert.equal(s.nextBillingAt,null);
assert.equal(snapshot(s,now+month+1).sandboxAccess,true);
assert.equal(snapshot(s,now+2*month).sandboxAccess,false);
assert.equal(snapshot(s,now+2*month).state,"expired");
s=apply(s,event({id:"e5",kind:"refunded",paymentId:"p2",at:now+month+2}));
assert.equal(snapshot(s,now+month+2).sandboxAccess,false);
assert.equal(snapshot(s,now+month+2).confirmedMinor,19900);
let t=apply(initial(order),event({id:"refund-first",kind:"refunded",at:now+1}));
t=apply(t,event());
assert.equal(snapshot(t,now).sandboxAccess,false);
t=apply(initial(order),event());
t=apply(t,event({id:"chargeback",kind:"disputed",at:now+1}));
assert.equal(snapshot(t,now+1).sandboxAccess,false);
assert.equal(snapshot(t,now+1).state,"disputed");
for(const state of [s,t])assert.equal(snapshot(state,now).liveAccess,false);
console.log("PASS: isolated subscription lifecycle; retries, renewals, cancellation, expiry, refunds, disputes, replay and live isolation.");
